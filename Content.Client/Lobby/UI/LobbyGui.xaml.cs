                ? "ui-lobby-expedition-ready-count-markup-blackhole"
                : "ui-lobby-expedition-ready-count-markup-server";
            ReadyCountLabel.SetMarkup(Loc.GetString(key,
                ("ready", _lastReadyCount),
                ("total", Math.Max(0, _lastPlayerCount))));
        }

        private void AnimatePalette(float t)
        {
            GetPaletteTargets(_bgMode,
                out var p, out var pBright, out var pDim, out var pMut, out var pFont,
                out var labelDim, out var labelHov, out var subDim, out var subLit,
                out var accentIdle, out var accentHover, out var lineIdle, out var lineLit,
                out var dashIdle, out var segEmpty);

            _p = Color.InterpolateBetween(_p, p, t);
            _pBright = Color.InterpolateBetween(_pBright, pBright, t);
            _pDim = Color.InterpolateBetween(_pDim, pDim, t);
            _pMut = Color.InterpolateBetween(_pMut, pMut, t);
            _pFont = Color.InterpolateBetween(_pFont, pFont, t);
            _labelDim = Color.InterpolateBetween(_labelDim, labelDim, t);
            _labelHov = Color.InterpolateBetween(_labelHov, labelHov, t);
            _subDim = Color.InterpolateBetween(_subDim, subDim, t);
            _subLit = Color.InterpolateBetween(_subLit, subLit, t);
            _accentIdle = Color.InterpolateBetween(_accentIdle, accentIdle, t);
            _accentHover = Color.InterpolateBetween(_accentHover, accentHover, t);
            _lineIdle = Color.InterpolateBetween(_lineIdle, lineIdle, t);
            _lineLit = Color.InterpolateBetween(_lineLit, lineLit, t);
            _dashIdle = Color.InterpolateBetween(_dashIdle, dashIdle, t);
            _segEmpty = Color.InterpolateBetween(_segEmpty, segEmpty, t);

            ApplyPaletteChrome(snap: false);
        }

