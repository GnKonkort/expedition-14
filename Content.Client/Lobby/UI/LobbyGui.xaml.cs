        private void AnimateReadyCounter(float dt)
        {
            var counterT = Math.Clamp(dt * CounterAnimSpeed, 0f, 1f);
            var badgeT = Math.Clamp(dt * BadgeAnimSpeed, 0f, 1f);
            var segT = Math.Clamp(dt * SegmentAnimSpeed, 0f, 1f);

            var counterTarget = _counterWanted ? 1f : 0f;
            _counterAnim = Lerp(_counterAnim, counterTarget, counterT);
            if (MathF.Abs(_counterAnim - counterTarget) < 0.001f)
                _counterAnim = counterTarget;

            var badgeTarget = _badgeWanted ? 1f : 0f;
            _badgeAnim = Lerp(_badgeAnim, badgeTarget, badgeT);
            if (MathF.Abs(_badgeAnim - badgeTarget) < 0.001f)
                _badgeAnim = badgeTarget;

            _segmentFillAnim = Lerp(_segmentFillAnim, _segmentFillTarget, segT);

            var counterEase = 1f - MathF.Pow(1f - _counterAnim, 2f);
            var badgeEase = 1f - MathF.Pow(1f - _badgeAnim, 2f);

            ReadyCounterBox.Visible = _counterWanted || _counterAnim > 0.01f;
            ReadyCounterBox.ModulateSelfOverride = Color.White.WithAlpha(counterEase);
            ReadyCounterBox.Margin = new Thickness(0, (1f - counterEase) * -8f, 0, 6);

            ReadyBadgeClip.MaxHeight = BadgeExpandedHeight * badgeEase;
            ReadyBadgeClip.ModulateSelfOverride = Color.White.WithAlpha(badgeEase);
            ReadyBadgeClip.Visible = badgeEase > 0.01f || _badgeWanted;

            var filled = _segmentFillAnim;
            for (var i = 0; i < ReadySegments; i++)
            {
                var segProgress = Math.Clamp(filled - i, 0f, 1f);
                Color color;
                if (segProgress <= 0.01f)
                    color = _segEmpty;
                else if (_readyTeal && i >= (int) filled - 1 && i < filled)
                    color = Color.InterpolateBetween(_p, ColorTeal, segProgress);
                else
                    color = Color.InterpolateBetween(_segEmpty, _p, segProgress);

                _readySegments[i].PanelOverride = new StyleBoxFlat { BackgroundColor = color };
                _readySegments[i].ModulateSelfOverride = Color.White.WithAlpha(0.35f + 0.65f * counterEase);
            }

            if (_badgeWanted || _badgeAnim > 0.01f)
            {
                _badgeBlinkT += dt;
                var on = (_badgeBlinkT % 1f) < 0.5f;
                ReadyBadgeDot.ModulateSelfOverride = Color.White.WithAlpha(on ? 1f : 0.15f);
            }
        }

        private void SelectNav(NavId id) => _selected = id;

        private void InitLobbyButtonSounds()
        {
            var volume = _cfg.GetCVar(CCVars.InterfaceVolume);
            _lobbyClickSource = CreateLobbyUiSource(LobbyClickPath, LobbyClickGain * volume);
            _lobbyReleaseSource = CreateLobbyUiSource(LobbyReleasePath, LobbyReleaseGain * volume);
            _lobbyHoverSource = CreateLobbyUiSource(LobbyHoverPath, LobbyHoverGain * volume);

            WireLobbyButtonSound(ReadyButton);
            WireLobbyButtonSound(CharacterNavButton);
            WireLobbyButtonSound(OptionsButton);
            WireLobbyButtonSound(LeaveButton);
            WireLobbyButtonSound(BgPrevButton);
            WireLobbyButtonSound(BgNextButton);
        }

        private IAudioSource? CreateLobbyUiSource(ResPath path, float gain)
        {
            if (!_resourceCache.TryGetResource(path, out AudioResource? resource))
                return null;

            var source = _audioManager.CreateAudioSource(resource);
            if (source == null)
                return null;

            source.Global = true;
            source.Gain = gain;
            return source;
        }

        private void WireLobbyButtonSound(Button button)
        {
            // Content must Ignore hits so the Button itself receives hover enter/exit.
            IgnoreMouseOnDescendants(button);

            // Mute default global UI click/hover — only Citadel lobby sounds here.
            button.MuteSounds = true;
            button.OnButtonDown += _ => _lobbyClickSource?.Restart();
            button.OnButtonUp += _ => _lobbyReleaseSource?.Restart();

            _lobbySoundButtons.Add(button);
            _lobbyButtonWasHovered[button] = false;
        }

        private static void IgnoreMouseOnDescendants(Control root)
        {
            foreach (var child in root.Children)
            {
                child.MouseFilter = MouseFilterMode.Ignore;
                IgnoreMouseOnDescendants(child);
            }
        }

        /// <summary>
        /// Plays hover when a lobby button becomes hovered. Uses IsHovered polling because
        /// nested content can steal OnMouseEntered even when click still reaches the button.
        /// </summary>
        private void UpdateLobbyButtonHoverSounds()
        {
            foreach (var button in _lobbySoundButtons)
            {
                var hovered = button.IsHovered;
                if (hovered && !_lobbyButtonWasHovered[button])
                    _lobbyHoverSource?.Restart();

                _lobbyButtonWasHovered[button] = hovered;
            }
        }

        private void WireHover(Button button, NavId id)
        {
            button.OnMouseEntered += _ => _hovered = id;
            button.OnMouseExited += _ =>
            {
                if (_hovered == id)
                    _hovered = null;
            };
        }

