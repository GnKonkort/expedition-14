        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);
            ChatMsgCount.Text = Loc.GetString("ui-lobby-expedition-chat-msg-count",
                ("count", Chat.Contents.EntryCount));

            var dt = args.DeltaSeconds;
            AnimatePalette(Math.Clamp(dt * PaletteAnimSpeed, 0f, 1f));
            AnimateNav(Math.Clamp(dt * NavAnimSpeed, 0f, 1f));
            AnimateReadyCounter(dt);
            UpdateLobbyButtonHoverSounds();
            UpdateChatResizeCursor();
        }

        public void SwitchState(LobbyGuiState state)
        {
            DefaultState.Visible = false;
            CharacterSetupState.Visible = false;

            switch (state)
            {
                case LobbyGuiState.Default:
                    DefaultState.Visible = true;
                    RightSide.Visible = true;
                    StatusPips.Visible = true;
                    FxOverlay.Visible = true;
                    ChatShell.Visible = true;
                    if (_selected == NavId.Character)
                        SelectNav(NavId.Play);
                    break;
                case LobbyGuiState.CharacterSetup:
                    CharacterSetupState.Visible = true;
                    ChatShell.Visible = false;
                    SelectNav(NavId.Character);

                    var actualWidth = (float) UserInterfaceManager.RootControl.PixelWidth;
                    var setupWidth = (float) LeftSide.PixelWidth;

                    if (1 - (setupWidth / actualWidth) > 0.30)
                        RightSide.Visible = false;

                    UserInterfaceManager.GetUIController<LobbyUIController>().ReloadCharacterSetup();
                    break;
            }
        }

        public void UpdateReadyVisuals(bool isGameStarted, bool areWeReady, int readyCount, int playerCount)
        {
            _gameStarted = isGameStarted;
            _readyTeal = !isGameStarted && areWeReady;

            var total = Math.Max(1, playerCount);
            _segmentFillTarget = readyCount / (float) total * ReadySegments;

            if (readyCount != _lastReadyCount || playerCount != _lastPlayerCount)
            {
                _lastReadyCount = readyCount;
                _lastPlayerCount = playerCount;
                RefreshReadyCountMarkup();
            }

            _counterWanted = !isGameStarted;
            _badgeWanted = !isGameStarted && areWeReady;
            ReadyCounterBox.Visible = _counterWanted || _counterAnim > 0.01f;

            PlaySubLabel.Text = Loc.GetString(
                !isGameStarted && areWeReady
                    ? "ui-lobby-expedition-play-sub-ready"
                    : isGameStarted
                        ? "ui-lobby-expedition-play-sub-join"
                        : "ui-lobby-expedition-play-sub");
        }

        private void OnBackgroundModeChanged(LobbyBgMode mode)
