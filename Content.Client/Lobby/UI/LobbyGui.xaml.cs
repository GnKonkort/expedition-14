        private static readonly Color ColorAccentHover = Color.FromHex("#FFCC60");
        private static readonly Color ColorLineIdle = Color.FromHex("#2A1A0880");
        private static readonly Color ColorLineLit = Color.FromHex("#F0A83033");

        private readonly PanelContainer[] _readySegments = new PanelContainer[ReadySegments];
        private readonly NavItem[] _navItems = new NavItem[4];

        private NavId? _selected;
