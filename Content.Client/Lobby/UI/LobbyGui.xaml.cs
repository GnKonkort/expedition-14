        private void AnimateNav(float t)
        {
            for (var i = 0; i < _navItems.Length; i++)
            {
                var id = (NavId) i;
                var item = _navItems[i];
                var selected = _selected == id;
                var hovered = _hovered == id;
                var playReady = id == NavId.Play && _readyTeal;

                float targetW = 3f;
                float targetH = 8f;
                var titleTarget = _labelDim;
                var subTarget = _subDim;
                var accentTarget = _accentIdle;
                var lineTarget = _lineIdle;

                if (playReady)
                {
                    targetW = 8f;
                    targetH = 32f;
                    titleTarget = ColorTeal;
                    subTarget = _subLit;
                    accentTarget = ColorTeal;
                    lineTarget = Color.FromHex("#4AF0D033");
                }
                else if (selected)
                {
                    targetW = 8f;
                    targetH = 32f;
                    titleTarget = _p;
                    subTarget = _subLit;
                    accentTarget = _p;
                    lineTarget = _lineLit;
                }
                else if (hovered)
                {
                    targetW = 8f;
                    targetH = 32f;
                    titleTarget = _labelHov;
                    subTarget = _subLit;
                    accentTarget = _accentHover;
                    lineTarget = _lineLit;
                }

                item.AccentW = Lerp(item.AccentW, targetW, t);
                item.AccentH = Lerp(item.AccentH, targetH, t);
                item.TitleColor = Color.InterpolateBetween(item.TitleColor, titleTarget, t);
                item.SubColor = Color.InterpolateBetween(item.SubColor, subTarget, t);
                item.AccentColor = Color.InterpolateBetween(item.AccentColor, accentTarget, t);
                item.LineColor = Color.InterpolateBetween(item.LineColor, lineTarget, t);

                var w = Math.Clamp(MathF.Round(item.AccentW), 3f, 8f);
                var h = Math.Clamp(MathF.Round(item.AccentH), 8f, 32f);
                item.Accent.MinSize = new Vector2(w, h);
                item.Accent.MaxSize = new Vector2(w, h);
                item.Accent.PanelOverride = new StyleBoxFlat { BackgroundColor = item.AccentColor };
                item.Title.FontColorOverride = item.TitleColor;
                item.Sub.FontColorOverride = item.SubColor;
                item.Hairline.PanelOverride = new StyleBoxFlat { BackgroundColor = item.LineColor };
            }
        }

        private static float Lerp(float a, float b, float t) => a + (b - a) * t;

        private void InitChatResize()
        {
            ChatResizeGrip.DefaultCursorShape = CursorShape.Crosshair;
            ChatResizeGrip.OnKeyBindDown += args =>
            {
                if (args.Function != EngineKeyFunctions.UIClick)
                    return;

                _chatResizing = true;
                _chatResizeMouseStart = args.PointerLocation.Position / UIScale;
                _chatResizeSizeStart = new Vector2(ChatShell.Width, ChatShell.Height);
                args.Handle();
            };

            ChatResizeGrip.OnKeyBindUp += args =>
            {
                if (args.Function != EngineKeyFunctions.UIClick)
                    return;
                _chatResizing = false;
            };
        }

        private void UpdateChatResizeCursor()
        {
            if (!_chatResizing)
                return;

            var mouse = UserInterfaceManager.MousePositionScaled.Position;
            var delta = mouse - _chatResizeMouseStart;
            var newW = Math.Clamp(_chatResizeSizeStart.X + delta.X, ChatShell.MinWidth, ChatShell.MaxWidth);
            var newH = Math.Clamp(_chatResizeSizeStart.Y - delta.Y, ChatShell.MinHeight, ChatShell.MaxHeight);
            ChatShell.SetSize = new Vector2(newW, newH);
        }

        protected override void KeyBindUp(GUIBoundKeyEventArgs args)
        {
            if (args.Function == EngineKeyFunctions.UIClick)
                _chatResizing = false;

            base.KeyBindUp(args);
        }

        protected override void MouseMove(GUIMouseMoveEventArgs args)
        {
            base.MouseMove(args);

            if (!_chatResizing)
                return;

            var delta = args.GlobalPosition - _chatResizeMouseStart;
            var newW = Math.Clamp(_chatResizeSizeStart.X + delta.X, ChatShell.MinWidth, ChatShell.MaxWidth);
            var newH = Math.Clamp(_chatResizeSizeStart.Y - delta.Y, ChatShell.MinHeight, ChatShell.MaxHeight);
            ChatShell.SetSize = new Vector2(newW, newH);
        }

