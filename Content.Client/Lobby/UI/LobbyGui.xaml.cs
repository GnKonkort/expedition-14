        private const float NavAnimSpeed = 12f;
        private const float CounterAnimSpeed = 8f;
        private const float BadgeAnimSpeed = 10f;
        private const float SegmentAnimSpeed = 6f;
        private const float BadgeExpandedHeight = 28f;

