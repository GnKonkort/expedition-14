using Robust.Shared.Maths;

namespace Content.Client._CitadelStation.Signboard.UI;

/// <summary>
/// Tiny 5×7 bitmap text stamp for signboard pixels (Latin + digits + basic punctuation).
/// Font styles tweak spacing/scale to approximate pixel / mono / round looks.
/// </summary>
public static class SignboardTextStamp
{
    // 5 columns × 7 rows, bit0 = top-left going right then down.
    private static readonly Dictionary<char, byte[]> Glyphs = BuildGlyphs();

    public static void Stamp(byte[] pixels, int width, int height, string text, Color color, int scale, int style, int originX = 2, int originY = -1)
    {
        scale = Math.Clamp(scale, 1, 4);
        var spacing = style switch
        {
            1 => 6, // mono-ish
            2 => 5, // round/compact
            _ => 6
        };

        var glyphW = 5 * scale;
        var glyphH = 7 * scale;
        var cursorX = originX;
        var cursorY = originY >= 0 ? originY : Math.Max(0, (height - glyphH) / 2);
        var gap = Math.Max(1, (spacing - 5) * scale + scale);
        var lineStartX = originX;

        foreach (var ch in text)
        {
            if (ch == '\n')
            {
                cursorX = lineStartX;
                cursorY += glyphH + scale;
                continue;
            }

            if (cursorX + glyphW >= width)
            {
                cursorX = lineStartX;
                cursorY += glyphH + scale;
            }

            if (cursorY + glyphH >= height)
                break;

            if (Glyphs.TryGetValue(char.ToUpperInvariant(ch), out var glyph))
                DrawGlyph(pixels, width, height, cursorX, cursorY, glyph, scale, color);
            else if (ch == ' ')
            {
                cursorX += glyphW + gap;
                continue;
            }

            cursorX += glyphW + gap;
        }
    }

    private static void DrawGlyph(byte[] pixels, int width, int height, int ox, int oy, byte[] glyph, int scale, Color color)
    {
        for (var gy = 0; gy < 7; gy++)
        {
            for (var gx = 0; gx < 5; gx++)
            {
                var bit = glyph[gy] & (1 << (4 - gx));
                if (bit == 0)
                    continue;

                for (var sy = 0; sy < scale; sy++)
                {
                    for (var sx = 0; sx < scale; sx++)
                    {
                        var x = ox + gx * scale + sx;
                        var y = oy + gy * scale + sy;
                        if (x < 0 || y < 0 || x >= width || y >= height)
                            continue;
                        var i = (y * width + x) * 4;
                        pixels[i] = (byte)(color.R * 255);
                        pixels[i + 1] = (byte)(color.G * 255);
                        pixels[i + 2] = (byte)(color.B * 255);
                        pixels[i + 3] = (byte)(color.A * 255);
                    }
                }
            }
        }
    }

    private static Dictionary<char, byte[]> BuildGlyphs()
    {
        // Each glyph: 7 bytes, bits 4..0 are columns left→right.
        var g = new Dictionary<char, byte[]>();
        void A(char c, params byte[] rows) => g[c] = rows;

        A('0', 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E);
        A('1', 0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E);
        A('2', 0x0E, 0x11, 0x01, 0x06, 0x08, 0x10, 0x1F);
        A('3', 0x0E, 0x11, 0x01, 0x06, 0x01, 0x11, 0x0E);
        A('4', 0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02);
        A('5', 0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E);
        A('6', 0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E);
        A('7', 0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08);
        A('8', 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E);
        A('9', 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C);

        A('A', 0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11);
        A('B', 0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E);
        A('C', 0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E);
        A('D', 0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E);
        A('E', 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F);
        A('F', 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10);
        A('G', 0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F);
        A('H', 0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11);
        A('I', 0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E);
        A('J', 0x01, 0x01, 0x01, 0x01, 0x11, 0x11, 0x0E);
        A('K', 0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11);
        A('L', 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F);
        A('M', 0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11);
        A('N', 0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11);
        A('O', 0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E);
        A('P', 0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10);
        A('Q', 0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D);
        A('R', 0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11);
        A('S', 0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E);
        A('T', 0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04);
        A('U', 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E);
        A('V', 0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04);
        A('W', 0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11);
        A('X', 0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11);
        A('Y', 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04);
        A('Z', 0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F);

        A('-', 0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00);
        A('+', 0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00);
        A('!', 0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04);
        A('?', 0x0E, 0x11, 0x01, 0x06, 0x04, 0x00, 0x04);
        A('.', 0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C);
        A(':', 0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00);
        A('/', 0x01, 0x02, 0x04, 0x04, 0x08, 0x10, 0x10);

        return g;
    }
}
